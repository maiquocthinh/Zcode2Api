const DICTS: Record<Lang, Dict> = { vi, en, ja, zh };

// Reactive module state (Svelte 5 runes in a.svelte.ts module): every
// template expression that calls t() re-renders when the language changes.
let current = $state<Lang>('vi');

/** Set the active language (also updates <html lang>). */
export function setLang(lang: Lang): void {
	current = LANGS.includes(lang) ? lang : 'vi';
	if (typeof document !== 'undefined') document.documentElement.lang = current;
}

/** Current language. */
export function getLang(): Lang {
	return current;
}

/** Translate `key` in the current language, interpolating {placeholders}. */
export function t(key: keyof Dict, params?: Record<string, string | number>): string {
	let s: string = DICTS[current][key] ?? DICTS.en[key] ?? String(key);
	if (params) {
		for (const [k, v] of Object.entries(params)) {
			s = s.replaceAll('{' + k + '}', String(v));
		}
	}
	return s;
}
